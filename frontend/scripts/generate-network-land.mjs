import { mkdir, writeFile } from 'node:fs/promises'
import { geoBounds, geoContains, geoEquirectangular } from 'd3-geo'
import { feature } from 'topojson-client'

// Natural Earth（公共领域）底图；固定版本与原地图相同，离线生成避免首访计算陆地网格。
const source = 'https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json'
const response = await fetch(source, { signal: AbortSignal.timeout(30000) })
if (!response.ok) throw new Error(`底图下载失败：${response.status}`)
const topology = await response.json()
const countries = feature(topology, topology.objects.countries).features
  .filter((country) => country.properties?.name !== 'Antarctica' && String(country.id) !== '010')
  .map((country) => ({ country, bounds: geoBounds(country) }))

// 与 TobNetworkMap 的固定投影、画布尺寸及原粒子间距保持一致。
const projection = geoEquirectangular().center([0, 0]).rotate([-150, 0, 0]).scale(185).translate([600, 300])
const dots = []
for (let latitude = -87; latitude <= 87; latitude += 2) {
  for (let longitude = -177; longitude <= 180; longitude += 2) {
    const point = [longitude, latitude]
    const onLand = countries.some(({ country, bounds: [[west, south], [east, north]] }) =>
      latitude >= south && latitude <= north
      && (west <= east ? longitude >= west && longitude <= east : longitude >= west || longitude <= east)
      && geoContains(country, point))
    if (!onLand) continue
    const [x, y] = projection(point)
    dots.push(`M${(x - 1.05).toFixed(3)},${y.toFixed(3)}a1.05,1.05 0 1,0 2.1,0a1.05,1.05 0 1,0 -2.1,0`)
  }
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 600">
<!-- Generated by scripts/generate-network-land.mjs from ${source}; Natural Earth public domain. -->
<path d="${dots.join('')}" fill="#8f938e" stroke="#8f938e" stroke-width=".35" opacity=".9" vector-effect="non-scaling-stroke"/>
</svg>
`
const target = new URL('../src/assets/network-land.svg', import.meta.url)
await mkdir(new URL('../src/assets/', import.meta.url), { recursive: true })
await writeFile(target, svg)
console.log(`已生成 ${dots.length} 个陆地点的静态底图`)
